<?php

declare(strict_types=1);

namespace Igne\LaravelBootUp\Deploy\Scripts;

use Igne\LaravelBootUp\Concerns\QuotesYamlScalars;
use Igne\LaravelBootUp\Contracts\ScriptGenerator;
use Igne\LaravelBootUp\Contracts\WritesDeployFile;
use Igne\LaravelBootUp\Data\DeploymentPlan;
use Igne\LaravelBootUp\Data\Lines;
use Igne\LaravelBootUp\Enums\BuiltInProcess;

/**
 * Renders fortrabbit's two command lists per environment: "Build commands"
 * (run after git receives the push, before the release — Composer
 * preinstalled, Node available) and "Post deploy commands" (run
 * sequentially after the release is live). By default they go into the
 * committed .fortrabbit/deploy.yml; in the terminal they are laid out for
 * pasting into the dashboard.
 */
final class FortrabbitScriptGenerator implements ScriptGenerator, WritesDeployFile
{
    use QuotesYamlScalars;

    private const string COMPOSER_FLAGS = '--prefer-dist --no-interaction --no-ansi --no-progress';

    private const string STORAGE_DIRECTORIES = 'mkdir -p storage/framework/cache storage/framework/sessions storage/framework/views';

    /**
     * A deploy file replaces the dashboard settings wholesale and an omitted
     * key falls back to fortrabbit's default rather than the dashboard's
     * value, so the file restates what the Laravel template configures there.
     * Without the /storage exclude, a replace deploy wipes persistent storage.
     */
    private const array CACHED_DIRECTORIES = ['vendor', 'node_modules', '.pnpm-store'];

    private const string DISTRIBUTION_STRATEGY = 'replace';

    private const array EXCLUDE_PATTERNS = ['/storage', '/node_modules'];

    public function key(): string
    {
        return 'fortrabbit';
    }

    public function label(): string
    {
        return 'Fortrabbit';
    }

    public function deployFilePath(): string
    {
        return '.fortrabbit/deploy.yml';
    }

    public function generate(DeploymentPlan $plan): Lines
    {
        $snippets = new DeployScriptSnippets($plan, artisan: 'php artisan', composer: 'composer');

        return $plan->inTerminal ? $this->dashboardCommands($snippets) : $this->deployFile($snippets);
    }

    private function dashboardCommands(DeployScriptSnippets $snippets): Lines
    {
        $environment = $snippets->plan->environment->value;

        return Lines::make()
            ->comment(
                "Fortrabbit deployment commands ({$environment})",
                'Generated by igne-agency/laravel-boot-up.',
                'Paste each section into the fortrabbit dashboard → your App →',
                "Deployment settings for the {$environment} environment.",
            )
            ->blank()
            ->heading('─── Build commands ────────────────────────────────────────────')
            ->lines($this->buildCommands($snippets))
            ->blank()
            ->heading('─── Post deploy commands ──────────────────────────────────────')
            ->lines($this->postDeployCommands($snippets));
    }

    private function deployFile(DeployScriptSnippets $snippets): Lines
    {
        return Lines::make()
            ->comment(
                "Fortrabbit deploy file ({$snippets->plan->environment->value})",
                'Generated by igne-agency/laravel-boot-up — commit it to the branch this environment deploys.',
            )
            ->warning(
                'Once on the deployed branch this file replaces ALL dashboard deployment settings;',
                "keys left out fall back to fortrabbit's defaults, not to the dashboard.",
            )
            ->line('apiVersion: 1.0')
            ->line('build:')
            ->indent(2, fn (Lines $yaml) => $yaml
                ->line('buildCommands:')
                ->indent(2, fn (Lines $yaml) => $yaml->lines($this->yamlList($this->buildCommands($snippets))))
                ->line('postDeployCommands:')
                ->indent(2, fn (Lines $yaml) => $yaml->lines($this->yamlList($this->postDeployCommands($snippets))))
                ->line('cachedDirectories:')
                ->indent(2, fn (Lines $yaml) => $yaml->lines($this->yamlList(Lines::make()->lines(self::CACHED_DIRECTORIES)))))
            ->line('distribution:')
            ->indent(2, fn (Lines $yaml) => $yaml
                ->line('strategy: '.self::DISTRIBUTION_STRATEGY)
                ->line('excludePatterns:')
                ->indent(2, fn (Lines $yaml) => $yaml->lines($this->yamlList(Lines::make()->lines(self::EXCLUDE_PATTERNS)))));
    }

    /**
     * The commands as YAML list items; comments and warnings stay comments.
     */
    private function yamlList(Lines $commands): Lines
    {
        return $commands->mapCommands($this->yamlListItem(...));
    }

    private function buildCommands(DeployScriptSnippets $snippets): Lines
    {
        $plan = $snippets->plan;

        return Lines::make()
            // Fortrabbit rebuilds the tree from git on every push, so the
            // gitignored storage directories are missing until recreated: here
            // for the build (Composer's package:discover boots the app), and
            // again in post deploy for the live release.
            ->line(self::STORAGE_DIRECTORIES)
            ->line($snippets->composerInstall(self::COMPOSER_FLAGS))
            ->when($plan->frontend, fn (Lines $script) => $script
                ->lines($plan->packageManager->buildScriptLines($plan->packageManagerVersion)));
    }

    private function postDeployCommands(DeployScriptSnippets $snippets): Lines
    {
        $plan = $snippets->plan;

        return Lines::make()
            // optimize, sessions and compiled views all write here.
            ->line(self::STORAGE_DIRECTORIES)
            ->lines($snippets->deployTasks($plan->beforeDeploy))
            ->lines($snippets->deployTasks($plan->beforeMigrations))
            ->lineIf($plan->migrate, $snippets->artisan('migrate --force'))
            ->lines($snippets->deployTasks($plan->afterMigrations))
            ->lineIf($plan->environment->optimize(), $snippets->artisan('optimize'))
            ->each($plan->finalize, fn (Lines $script, string $command) => $script
                ->line($snippets->artisan($command)))
            ->lines($snippets->deployTasks($plan->afterDeploy))
            ->each($plan->restarts, fn (Lines $script, BuiltInProcess $process) => $script
                ->line($snippets->artisan((string) $process->restartCommand())));
    }
}
