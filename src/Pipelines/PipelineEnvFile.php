<?php

declare(strict_types=1);

namespace Igne\LaravelBootUp\Pipelines;

use Igne\LaravelBootUp\Data\Lines;

/**
 * Renders a fresh .env.pipeline: the committed CI test environment the
 * generated pipelines copy over .env. Deliberately not Environment\EnvFile,
 * which line-edits an existing file.
 */
final class PipelineEnvFile
{
    /** Template keys that open a new block, separated from the previous one by a blank line. */
    private const array BLOCK_STARTS = ['LOG_CHANNEL', 'DB_CONNECTION', 'BROADCAST_CONNECTION'];

    public function path(): string
    {
        return '.env.pipeline';
    }

    /**
     * @param  array<string, scalar|null>  $overrides  written verbatim; template keys are replaced in place, new keys appended as a final block
     */
    public function generate(?string $appKey = null, array $overrides = []): string
    {
        $template = $this->template($appKey ?? self::randomKey());
        $values = [...$template, ...array_map(self::value(...), $overrides)];
        $firstAppended = array_key_first(array_diff_key($values, $template));

        return Lines::make()
            ->comment(
                'CI test environment — generated by igne-agency/laravel-boot-up.',
                'The pipeline copies this file over .env. Commit it; the APP_KEY is only ever used in CI.',
            )
            ->blank()
            ->each($values, fn (Lines $lines, string $value, string $key) => $lines
                ->when(in_array($key, self::BLOCK_STARTS, true) || $key === $firstAppended, fn (Lines $lines) => $lines->blank())
                ->line("{$key}={$value}"))
            ->render();
    }

    /**
     * @return array<string, string>
     */
    private function template(string $appKey): array
    {
        return [
            'APP_NAME' => 'Laravel',
            'APP_ENV' => 'testing',
            'APP_KEY' => $appKey,
            'APP_DEBUG' => 'true',
            'APP_URL' => 'http://localhost',
            'LOG_CHANNEL' => 'stderr',
            'DB_CONNECTION' => 'sqlite',
            'DB_DATABASE' => ':memory:',
            'BROADCAST_CONNECTION' => 'log',
            'CACHE_STORE' => 'array',
            'SESSION_DRIVER' => 'array',
            'QUEUE_CONNECTION' => 'sync',
            'MAIL_MAILER' => 'array',
        ];
    }

    private static function value(bool|int|float|string|null $value): string
    {
        return match (true) {
            $value === null => '',
            is_bool($value) => $value ? 'true' : 'false',
            default => (string) $value,
        };
    }

    /**
     * The exact format `php artisan key:generate` produces.
     */
    public static function randomKey(): string
    {
        return 'base64:'.base64_encode(random_bytes(32));
    }

    /**
     * The APP_KEY found in existing .env.pipeline contents, or null when the
     * key is absent or present but empty — so callers can preserve a set key
     * across regeneration and only mint a fresh one when there isn't one.
     */
    public function currentAppKey(string $contents): ?string
    {
        if (preg_match('/^APP_KEY[ \t]*=[ \t]*(.*)$/m', $contents, $matches) !== 1) {
            return null;
        }

        $value = trim($matches[1]);

        return $value === '' ? null : $value;
    }
}
