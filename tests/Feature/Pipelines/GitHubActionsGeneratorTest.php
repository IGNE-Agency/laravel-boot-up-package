function githubPipelinePlan(array $overrides = [], array $deploymentOverrides = []): PipelinePlan
{
    $deploymentDefaults = [
        'environment' => DeploymentEnvironment::DEVELOPMENT,
        'migrate' => true,
        'finalize' => ['storage:link'],
        'beforeMigrations' => [],
        'afterMigrations' => [],
        'frontend' => true,
        'packageManager' => PackageManager::NPM,
        'restartQueues' => true,
    ];

    $defaults = [
        'deployment' => new DeploymentPlan(...array_merge($deploymentDefaults, $deploymentOverrides)),
        'nova' => true,
        'pint' => true,
        'phpVersion' => '8.4',
        'branchEnvironments' => [
            'develop' => 'development',
            'staging' => 'staging',
            'main' => 'production',
        ],
        'host' => DeployHookHost::FORTRABBIT,
    ];

    return new PipelinePlan(...array_merge($defaults, $overrides));
}

function githubGenerator(): GitHubActionsGenerator
{
    return new GitHubActionsGenerator(new CiScripts);
}

function githubWorkflow(PipelinePlan $plan): string
{
    return githubGenerator()->files($plan)[0]->contents;
}

test('renders the full workflow for a nova project with pint', function (): void {
    $yaml = githubWorkflow(githubPipelinePlan());

    expect($yaml)->toBe(<<<'YAML'
# CI/CD pipeline (GitHub Actions)
# Generated by igne-agency/laravel-boot-up — lives at .github/workflows/ci.yml.
# Checks run on pull requests and on pushes to develop, staging and main;
# a green push then triggers its environment's deploy hook via
# scripts/ci/deploy-hook.sh (skipped when DEPLOY_HOOK is unset).

name: CI/CD

on:
  push:
    branches: [develop, staging, main]
  pull_request:

permissions:
  contents: read

# Superseded pull-request runs are cancelled; push runs never are — they deploy.
concurrency:
  group: ${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: ${{ github.event_name == 'pull_request' }}

jobs:
  lint:
    name: Lint
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@v5

      - name: Set up PHP
        uses: shivammathur/setup-php@v2
        with:
          php-version: '8.4'
          extensions: mbstring, dom, fileinfo, sqlite3, pdo_sqlite
          coverage: none

      - name: Determine the composer cache directory
        id: composer-cache
        run: echo "dir=$(composer config cache-files-dir)" >> "$GITHUB_OUTPUT"

      - name: Cache composer dependencies
        uses: actions/cache@v5
        with:
          path: ${{ steps.composer-cache.outputs.dir }}
          key: composer-${{ hashFiles('composer.lock') }}
          restore-keys: composer-

      - name: Check the code style
        env:
          COMPOSER_AUTH: ${{ secrets.COMPOSER_AUTH }}
        run: bash scripts/ci/lint.sh

  build:
    name: Build
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@v5

      - name: Set up PHP
        uses: shivammathur/setup-php@v2
        with:
          php-version: '8.4'
          extensions: mbstring, dom, fileinfo, sqlite3, pdo_sqlite
          coverage: none

      - name: Determine the composer cache directory
        id: composer-cache
        run: echo "dir=$(composer config cache-files-dir)" >> "$GITHUB_OUTPUT"

      - name: Cache composer dependencies
        uses: actions/cache@v5
        with:
          path: ${{ steps.composer-cache.outputs.dir }}
          key: composer-${{ hashFiles('composer.lock') }}
          restore-keys: composer-

      - name: Build the frontend and framework caches
        env:
          COMPOSER_AUTH: ${{ secrets.COMPOSER_AUTH }}
        run: bash scripts/ci/build.sh

  test:
    name: Test
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v5

      - name: Set up PHP
        uses: shivammathur/setup-php@v2
        with:
          php-version: '8.4'
          extensions: mbstring, dom, fileinfo, sqlite3, pdo_sqlite
          coverage: none

      - name: Determine the composer cache directory
        id: composer-cache
        run: echo "dir=$(composer config cache-files-dir)" >> "$GITHUB_OUTPUT"

      - name: Cache composer dependencies
        uses: actions/cache@v5
        with:
          path: ${{ steps.composer-cache.outputs.dir }}
          key: composer-${{ hashFiles('composer.lock') }}
          restore-keys: composer-

      - name: Run the test suite
        env:
          COMPOSER_AUTH: ${{ secrets.COMPOSER_AUTH }}
        run: bash scripts/ci/test.sh

  deploy-development:
    name: Deploy (development)
    needs: [lint, build, test]
    if: github.event_name == 'push' && github.ref == 'refs/heads/develop'
    runs-on: ubuntu-latest
    timeout-minutes: 5
    environment: development
    concurrency:
      group: deployment-development
      cancel-in-progress: false
    steps:
      - uses: actions/checkout@v5
        with:
          sparse-checkout: scripts/ci

      - name: Trigger the development deploy hook
        env:
          DEPLOY_HOOK: ${{ secrets.DEPLOY_HOOK }}
        run: bash scripts/ci/deploy-hook.sh development "${DEPLOY_HOOK:-}"

  deploy-staging:
    name: Deploy (staging)
    needs: [lint, build, test]
    if: github.event_name == 'push' && github.ref == 'refs/heads/staging'
    runs-on: ubuntu-latest
    timeout-minutes: 5
    environment: staging
    concurrency:
      group: deployment-staging
      cancel-in-progress: false
    steps:
      - uses: actions/checkout@v5
        with:
          sparse-checkout: scripts/ci

      - name: Trigger the staging deploy hook
        env:
          DEPLOY_HOOK: ${{ secrets.DEPLOY_HOOK }}
        run: bash scripts/ci/deploy-hook.sh staging "${DEPLOY_HOOK:-}"

  deploy-production:
    name: Deploy (production)
    needs: [lint, build, test]
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    runs-on: ubuntu-latest
    timeout-minutes: 5
