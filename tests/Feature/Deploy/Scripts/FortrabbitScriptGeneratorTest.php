test('renders bound commands for all four phases in the canonical order', function (): void {
    $script = fortrabbitScript([
        'beforeDeploy' => [DeployTask::artisan('pennant:purge')],
        'beforeMigrations' => [DeployTask::artisan('wayfinder:generate')],
        'afterMigrations' => [DeployTask::artisan('model:typer')],
        'afterDeploy' => [DeployTask::artisan('cache:warm')],
    ]);

    expect($script)
        ->toContain('php artisan pennant:purge')
        ->toContain('php artisan wayfinder:generate')
        ->toContain('php artisan model:typer')
        ->toContain('php artisan cache:warm');

    // the storage directories open the post-deploy section; before-deploy runs
    // before migrations; after-deploy runs after finalize.
    $postDeploy = substr($script, (int) strpos($script, 'postDeployCommands:'));

    expect(strpos($postDeploy, 'mkdir -p storage/framework'))->toBeLessThan(strpos($postDeploy, 'pennant:purge'))
        ->and(strpos($script, 'pennant:purge'))->toBeLessThan(strpos($script, 'migrate --force'))
        ->and(strpos($script, 'cache:warm'))->toBeGreaterThan(strpos($script, 'storage:link'));
});

test('no package manager is installed globally, in the file or the terminal', function (PackageManager $manager): void {
    expect(fortrabbitScript(['packageManager' => $manager]))->not->toContain(' -g ')
        ->and(fortrabbitScript(['packageManager' => $manager, 'inTerminal' => true]))->not->toContain(' -g ');
})->with(PackageManager::cases());

