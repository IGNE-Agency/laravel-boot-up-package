function fortrabbitPlan(array $overrides = []): DeploymentPlan
{
    $defaults = [
        'environment' => DeploymentEnvironment::Production,
        'migrate' => true,
        'finalize' => ['storage:link'],
        'beforeMigrations' => [],
        'afterMigrations' => [],
        'frontend' => true,
        'packageManager' => PackageManager::Pnpm,
        'restarts' => [BuiltInProcess::Queue],
    ];

    return new DeploymentPlan(...array_merge($defaults, $overrides));
}

function fortrabbitScript(array $overrides = [], FortrabbitConfig $config = new FortrabbitConfig): string
{
    return (new FortrabbitScriptGenerator($config))->generate(fortrabbitPlan($overrides))->render();
}

test('renders the deploy file for production with a pinned yarn', function (): void {
    $script = fortrabbitScript([
        'packageManager' => PackageManager::Yarn,
        'packageManagerVersion' => '4.10.3',
    ]);

    expect($script)->toBe(<<<'SCRIPT'
# Fortrabbit deploy file (production)
# Generated by igne-agency/laravel-boot-up — commit it to the branch this environment deploys.
#! Once on the deployed branch this file replaces ALL dashboard deployment settings;
#! keys left out fall back to fortrabbit's defaults, not to the dashboard.
apiVersion: 1.0
build:
  buildCommands:
    - mkdir -p storage/framework/cache storage/framework/sessions storage/framework/views
    - composer install --no-dev --prefer-dist --no-interaction --no-ansi --no-progress
    - npx --yes corepack yarn install --immutable || npx --yes corepack yarn install
    - npx --yes corepack yarn run build
  postDeployCommands:
    - mkdir -p storage/framework/cache storage/framework/sessions storage/framework/views
    - php artisan migrate --force
    - php artisan optimize
    - php artisan storage:link
    - php artisan queue:restart
  cachedDirectories:
    - vendor
    - node_modules
    - .pnpm-store
distribution:
  strategy: replace
  excludePatterns:
    - /storage
    - /node_modules

SCRIPT);
});

test('the deploy file is valid YAML in the shape fortrabbit reads', function (): void {
    $file = Yaml::parse(fortrabbitScript([
        'beforeMigrations' => [DeployTask::artisan('wayfinder:generate', 'Generating routes...')],
    ]));

    expect($file['apiVersion'])->toBe(1.0)
        ->and($file['build']['buildCommands'])->toBe([
            'mkdir -p storage/framework/cache storage/framework/sessions storage/framework/views',
            'composer install --no-dev --prefer-dist --no-interaction --no-ansi --no-progress',
            'npx --yes corepack pnpm install --frozen-lockfile || npx --yes corepack pnpm install',
            'npx --yes corepack pnpm run build',
        ])
        ->and($file['build']['postDeployCommands'])->toContain('php artisan wayfinder:generate')
        ->and($file['build']['cachedDirectories'])->toBe(['vendor', 'node_modules', '.pnpm-store'])
        ->and($file['distribution'])->toBe([
            'strategy' => 'replace',
            'excludePatterns' => ['/storage', '/node_modules'],
        ]);
});

